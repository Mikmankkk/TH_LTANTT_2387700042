import {chromium} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';
const browser=await chromium.launch({channel:process.env.CI?'chromium':'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const base='http://127.0.0.1:3000/TH_LTANTT_2387700042/';
const response=await page.goto(base,{waitUntil:'networkidle'});
if(response.status()!==200)throw new Error(`HTTP ${response.status()}`);
await page.getByRole('heading',{name:'Chạy nhanh. Kiểm soát bảo mật.'}).waitFor();
mkdirSync('evidence',{recursive:true});
await page.screenshot({path:'evidence/05-website-desktop.png',fullPage:true});
await page.getByRole('link',{name:'Đọc báo cáo thực hành →'}).click();
await page.getByRole('heading',{name:'Bảo mật với DevSecOps',exact:true}).waitFor();
await page.screenshot({path:'evidence/06-website-report.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto(base,{waitUntil:'networkidle'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Mobile horizontal overflow');
await page.screenshot({path:'evidence/07-website-mobile.png',fullPage:true});
if(errors.length)throw new Error(errors.join('\n'));
mkdirSync('reports',{recursive:true});
writeFileSync('reports/browser.json',JSON.stringify({time:new Date().toISOString(),checks:['home HTTP 200','heading visible','report navigation','mobile no horizontal overflow','no JavaScript page errors'],errors},null,2));
console.log('Browser: 5 checks PASS; 3 screenshots saved');
await browser.close();
